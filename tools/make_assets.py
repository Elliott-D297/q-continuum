#!/usr/bin/env python3
"""Regenerate the subsetted fonts and src/icons.h.
usage: make_assets.py <plex-ttf-dir> <antonio-woff-dir> <lucide-static-package-dir> <q-continuum-root>
(Antonio: the files/ folder of the @fontsource/antonio npm package)
Needs: pip install fonttools"""
import json, os, subprocess, sys

plex, antonio, lucide, root = sys.argv[1:5]
out = os.path.join(root, "assets", "fonts")
os.makedirs(out, exist_ok=True)

# Latin-1 + the symbols the UI uses (units, Greek letters for physics, arrows, ellipsis ...)
TEXT = "U+0020-007E,U+00A0-00FF,U+2013,U+2014,U+2018,U+2019,U+201C,U+201D,U+2022,U+2026,U+2190-2193,U+2192," \
       "U+00B0,U+00B2,U+00B3,U+00B5,U+00D7,U+0394,U+03B1,U+03B2,U+03B5,U+03BA,U+03BC,U+03BD,U+03C1,U+03C3,U+03C9," \
       "U+03C6,U+2207,U+2248,U+2264,U+2265,U+2212,U+00B7,U+2713,U+2192"

def subset(src, dst, unicodes):
    subprocess.check_call(["pyftsubset", src, "--unicodes=" + unicodes, "--output-file=" + dst,
                           "--layout-features=kern,liga,calt,tnum", "--no-hinting", "--desubroutinize"])
    print(f"{os.path.basename(dst)}: {os.path.getsize(dst)/1024:.0f} KB")

for w in ["Regular", "Medium", "SemiBold"]:
    subset(os.path.join(plex, f"IBMPlexSans-{w}.ttf"), os.path.join(out, f"IBMPlexSans-{w}.ttf"), TEXT)
for w in ["Regular", "Medium"]:
    subset(os.path.join(plex, f"IBMPlexMono-{w}.ttf"), os.path.join(out, f"IBMPlexMono-{w}.ttf"), TEXT)
# Antonio (condensed, for the LCARS-style interface): woff -> ttf while subsetting
ANT = "U+0020-007E,U+00A0-00FF,U+2013,U+2014,U+2018,U+2019,U+201C,U+201D,U+2022,U+2026,U+2190-2193,U+00B0,U+00B2,U+00B3,U+00B5,U+00D7,U+2212,U+00B7"
for w, name in [(400, "Regular"), (500, "Medium"), (700, "Bold")]:
    subprocess.check_call(["pyftsubset", os.path.join(antonio, f"antonio-latin-{w}-normal.woff"), "--unicodes=" + ANT,
                           "--flavor=", "--output-file=" + os.path.join(out, f"Antonio-{name}.ttf"),
                           "--layout-features=kern,tnum", "--no-hinting"])

ICONS = """folder folder-open folder-plus play square rotate-ccw settings box grid-3x3 wind thermometer droplets
flame sun activity terminal external-link copy trash-2 plus search chevron-right chevron-down chevron-left chevron-up
check x triangle-alert info file-text layers sliders-horizontal cpu sigma gauge house library book-open save
refresh-cw octagon-x loader-circle clock hard-drive monitor chart-line table circle-check circle-x circle-dot zap
waves sparkles git-fork list eye pencil undo-2 filter pause hash file-code braces arrow-right arrow-left
square-terminal panel-left boxes orbit atom workflow keyboard moon sun-medium wrench rocket fan""".split()
info = json.load(open(os.path.join(lucide, "font", "info.json")))
cps = []
lines = ["/* generated by tools/make_assets.py -- Lucide icons (ISC licence), UTF-8 strings for DrawTextEx */",
         "#ifndef PL_ICONS_H", "#define PL_ICONS_H", ""]
for name in ICONS:
    cp = int(info[name]["encodedCode"].lstrip("\\"), 16)
    cps.append(cp)
    utf8 = chr(cp).encode("utf-8")
    macro = "ICON_" + name.upper().replace("-", "_")
    lines.append(f'#define {macro:<26} "' + "".join(f"\\x{b:02x}" for b in utf8) + f'"   /* U+{cp:04X} */')
lines += ["", "static const int PL_ICON_CODEPOINTS[] = {",
          "    " + ", ".join(f"0x{c:04X}" for c in cps), "};",
          f"#define PL_ICON_COUNT {len(cps)}", "", "#endif", ""]
open(os.path.join(root, "src", "icons.h"), "w").write("\n".join(lines))
subset(os.path.join(lucide, "font", "lucide.ttf"), os.path.join(out, "lucide.ttf"), ",".join(f"U+{c:04X}" for c in cps))
